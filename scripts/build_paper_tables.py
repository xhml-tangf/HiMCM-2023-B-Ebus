"""Generate every manuscript number from canonical_v4.json."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results/research_model"
OUT = ROOT / "paper/generated"


def macro_name(key: str) -> str:
    safe = key.replace("\\", "/").replace("{", "").replace("}", "")
    return "canonical@" + safe


def write_macros(flat: dict[str, str]) -> None:
    lines = ["% Generated by scripts/build_paper_tables.py; do not edit."]
    for key, value in sorted(flat.items()):
        lines.append(f"\\expandafter\\def\\csname {macro_name(key)}\\endcsname{{{value}}}")
    lines.append("\\newcommand{\\CV}[1]{\\ifcsname " + "canonical@#1" + "\\endcsname\\csname " + "canonical@#1" + "\\endcsname\\else\\textbf{??}\\fi}")
    (OUT / "canonical_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def latex_escape(value: object) -> str:
    s = str(value)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    d = json.loads((RES / "canonical_v4.json").read_text(encoding="utf-8"))
    rec = d["transition"]["recommended"]
    life = d["lifecycle_scores"]["recommended_detail"]
    sched = d["schedule"]
    ledger_path = RES / rec["ledger_file"]
    ledger = pd.read_csv(ledger_path)
    yearly = ledger.groupby("year").agg(
        ev=("acquired_electric", "sum"), conv=("acquired_conventional", "sum"),
        retire=("retired", "sum"), stock=("electric_stock", "sum"),
        conv_stock=("conventional_stock", "sum"),
    ).reindex(range(2024, 2034), fill_value=0)
    grants = {int(round(x["grant_fraction"] * 100)): x for x in rec["grants"]}

    flat = {
        "schedule.fleet_with_spares": f"{sched['fleet_with_spares']:,}",
        "schedule.active_battery_buses": f"{sched['active_buses']:,}",
        "schedule.reserve_buses": f"{sched['fleet_with_spares']-sched['active_buses']:,}",
        "schedule.total_electric_stock": f"{sched['fleet_with_spares']+275:,}",
        "schedule.required_peak_power_mw": f"{sched['firm_power_mw_conservative_sum']:.2f}",
        "schedule.annual_grid_gwh": f"{sched['annual_grid_gwh']:.1f}",
        "schedule.annual_revenue_km": f"{sched['annual_revenue_km']/1e6:.2f} million",
        "schedule.active_buses": f"{sched['active_buses']:,}",
        "schedule.non_trolley_trip_instances": f"{sched['calendar_trip_instances']:,}",
        "transition.total_battery_purchases": f"{sum(rec['annual_electric_purchases']):,}",
        "transition.peak_annual_deliveries": f"{max(rec['annual_electric_purchases']):,}",
        "transition.plan_gross_pv_billion": f"{rec['plan_pv_cad']/1e9:.3f}",
        "transition.baseline_gross_pv_billion": f"{rec['baseline_pv_cad']/1e9:.3f}",
        "transition.economic_score_pct": f"{rec['economic_score_pct']:.2f}",
        "transition.agency_25_pv_billion": f"{grants[25]['plan_agency_pv_cad']/1e9:.3f}",
        "transition.agency_50_pv_billion": f"{grants[50]['plan_agency_pv_cad']/1e9:.3f}",
        "transition.agency_50_economic_pct": f"{grants[50]['economic_score_pct']:.2f}",
        "lifecycle.environment_score_pct": f"{life['environmental_score_pct']:.2f}",
        "lifecycle.whole_fleet_environment_score_pct": f"{life['whole_fleet_with_common_trolley']['environmental_score_pct']:.2f}",
        "lifecycle.operation_reduction_pct": f"{life['operation_score_2033_pct']:.2f}",
        "lifecycle.plan_annual_emissions_t": f"{life['plan_total_t_year']:,.0f}",
        "lifecycle.baseline_annual_emissions_t": f"{life['baseline_total_t_year']:,.0f}",
        "lifecycle.transition_score_pct": f"{rec['environmental_score_pct']:.2f}",
        "lifecycle.transition_emissions_t": f"{rec['plan_ghg_t']:,.0f}",
        "lifecycle.baseline_transition_emissions_t": f"{rec['baseline_ghg_t']:,.0f}",
        "lifecycle.plan_gco2e_per_service_km": f"{life['plan_gco2e_per_service_km']:.1f}",
        "lifecycle.baseline_gco2e_per_service_km": f"{life['baseline_gco2e_per_service_km']:.1f}",
    }
    for stem in ("transition", "finance"):
        flat[f"{stem}.plan_gross_pv_billion"] = flat["transition.plan_gross_pv_billion"]
        flat[f"{stem}.baseline_gross_pv_billion"] = flat["transition.baseline_gross_pv_billion"]
        flat[f"{stem}.economic_score_pct"] = flat["transition.economic_score_pct"]
        flat[f"{stem}.agency_25_pv_billion"] = flat["transition.agency_25_pv_billion"]
        flat[f"{stem}.agency_50_pv_billion"] = flat["transition.agency_50_pv_billion"]
    schedule_full = json.loads((RES / (d.get("source_transition", "canonical_transition.json").replace("_transition.json", "_schedule.json"))).read_text(encoding="utf-8")) if (RES / d.get("source_transition", "canonical_transition.json").replace("_transition.json", "_schedule.json")).exists() else None
    if schedule_full is None:
        schedule_full = json.loads((RES / "central_schedule.json").read_text(encoding="utf-8"))
    alias = {"North_Shore": "NorthShore", "Port_Coquitlam": "PortCoquitlam"}
    by_site = {}
    for p in schedule_full["outputs"]["electric"]["packages"]:
        site = alias.get(p["site"], p["site"])
        row = by_site.setdefault(site, {"buses": 0, "active": 0, "ports": 0, "mw": 0.0})
        row["buses"] += int(p["fleet_with_spares"])
        row["active"] += int(p["active_buses"])
        row["ports"] += int(p["dedicated_ports"])
        row["mw"] += float(p["required_power_kw"]) / 1000
    for site, row in by_site.items():
        flat[f"depot.{site}.buses"] = f"{row['buses']:,}"
        flat[f"depot.{site}.reserve"] = f"{row['buses']-row['active']:,}"
        flat[f"depot.{site}.ports"] = f"{row['ports']:,}"
        flat[f"depot.{site}.mw"] = f"{row['mw']:.2f}"
    for y, row in yearly.iterrows():
        flat[f"roadmap.{y}.ev"] = f"{int(row.ev):,}"
        flat[f"roadmap.{y}.conv"] = f"{int(row.conv):,}"
        flat[f"roadmap.{y}.retire"] = f"{int(row.retire):,}"
        flat[f"roadmap.{y}.stock"] = f"{int(row.stock):,}"
    for slug, row in {
        "central": d.get("sensitivity", [{}])[0] if d.get("sensitivity") else {},
        "spare10": next((x for x in d.get("sensitivity", []) if "ten" in x.get("label", "")), {}),
        "newbuild": next((x for x in d.get("sensitivity", []) if "new" in x.get("label", "")), {}),
        "slow": next((x for x in d.get("sensitivity", []) if "half" in x.get("label", "")), {}),
        "winter": next((x for x in d.get("sensitivity", []) if "winter" in x.get("label", "")), {}),
        "fossil": next((x for x in d.get("sensitivity", []) if "fossil" in x.get("label", "")), {}),
    }.items():
        flat[f"sens.{slug}.econ"] = f"{row.get('economic_score_pct', 0):.2f}" if row else "--"
        flat[f"sens.{slug}.env"] = f"{row.get('full_life_environment_score_pct', 0):.2f}" if row and row.get('full_life_environment_score_pct') is not None else "--"
        flat[f"sens.{slug}.power"] = f"{row.get('required_power_mw', 0):.2f}" if row else "--"
    for city in d["city_comparison"]["cities"]:
        slug = city["city"].lower()
        flat[f"{slug}.fleet"] = f"{city['fleet_slots']:,}"
        flat[f"{slug}.existing_electric"] = f"{city['existing_electric']:,}"
        flat[f"{slug}.non_electric"] = f"{city['conventional_slots']:,}"
        flat[f"{slug}.peak_ev_deliveries"] = f"{city['peak_or_required_annual_delivery']:,}"
        if city.get("annual_service_km") is not None:
            flat[f"{slug}.service_million_km"] = f"{city['annual_service_km']/1e6:.2f}"
        score = city.get("lifecycle_environmental_score_pct")
        flat[f"{slug}.lifecycle_score"] = "--" if score is None else f"{score:.2f}\\%"
    flat["vancouver.fleet"] = "1,725"
    flat["vancouver.existing_electric"] = "280"
    flat["vancouver.non_electric"] = "1,445"
    flat["vancouver.peak_ev_deliveries"] = flat["transition.peak_annual_deliveries"]
    flat["vancouver.lifecycle_score"] = flat["lifecycle.environment_score_pct"] + "\\%"
    flat["chicago.fleet"] = "1,875"
    flat["chicago.existing_electric"] = "25"
    flat["chicago.non_electric"] = "1,850"
    flat["london.fleet"] = "8,643"
    flat["london.existing_electric"] = "950"
    flat["london.non_electric"] = "7,693"
    flat.setdefault("london.service_million_km", "fleet case")
    flat.setdefault("chicago.lifecycle_score", "fleet case")
    flat.setdefault("london.lifecycle_score", "fleet case")
    write_macros(flat)

    (OUT / "vancouver_scores.tex").write_text(
        "\\begin{table}[htbp]\n\\centering\n"
        "\\caption{Service, fleet, finance and full-lifecycle results for the recommended Vancouver plan.}\n"
        "\\begin{tabular}{lr}\n\\toprule\nIndicator & Result\\\\\\midrule\n"
        f"Battery buses including reserve & {flat['schedule.fleet_with_spares']}\\\\\n"
        "Retained trolleybuses & 275\\\\\n"
        f"Required firm depot power & {flat['schedule.required_peak_power_mw']} MW\\\\\n"
        f"Annual grid energy & {flat['schedule.annual_grid_gwh']} GWh\\\\\n"
        f"Peak annual EV delivery & {flat['transition.peak_annual_deliveries']}\\\\\n"
        f"Ten-year gross PV, baseline & CAD {flat['transition.baseline_gross_pv_billion']} bn\\\\\n"
        f"Ten-year gross PV, electric plan & CAD {flat['transition.plan_gross_pv_billion']} bn\\\\\n"
        f"Economic score, unsubsidized & {flat['transition.economic_score_pct']}\\%\\\\\n"
        f"Agency cost with 50\\% capital support & CAD {flat['transition.agency_50_pv_billion']} bn\\\\\n"
        f"Full-lifecycle environmental score & {flat['lifecycle.environment_score_pct']}\\%\\\\\n"
        f"2033 operating emission reduction & {flat['lifecycle.operation_reduction_pct']}\\%\\\\\n"
        f"2024--2033 transition emissions & {flat['lifecycle.transition_emissions_t']} t CO$_2$e\\\\\n"
        "\\bottomrule\n\\end{tabular}\n\\end{table}\n", encoding="utf-8")

    rows = []
    for y, row in yearly.iterrows():
        rows.append(f"{y} & {int(row.ev):,} & {int(row.conv):,} & {int(row.retire):,} & {int(row.stock):,} & {int(row.conv_stock):,}\\\\")
    (OUT / "vancouver_roadmap.tex").write_text(
        "\\begin{table}[htbp]\n\\centering\n\\caption{Recommended annual purchase, retirement and fleet path.}\n"
        "\\begin{tabular}{rrrrrr}\n\\toprule\nYear & EV purchases & Conventional purchases & Retirements & Electric stock & Conventional stock\\\\\\midrule\n"
        + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n", encoding="utf-8")

    # Sensitivity claims are generated from the canonical table only.
    sens_rows = []
    for item in d.get("sensitivity", []):
        if item.get("label") in {"primary_transition", "canonical_transition", "ten_percent_reserve",
                                 "full_new_depots", "half_power", "winter_stress", "fossil_sensitivity"}:
            sens_rows.append(item)
    lines = ["\\begin{table}[htbp]", "\\centering",
             "\\caption{One-factor robustness of the recommended service plan.}",
             "\\begin{tabularx}{\\linewidth}{@{}Xrrr@{}}", "\\toprule",
             "Case & Economic score & Full-life environment & Peak power (MW)\\\\", "\\midrule"]
    for item in sens_rows:
        label = item.get("label", "case").replace("_", "\\_")
        env = item.get("full_life_environment_score_pct")
        power = item.get("required_power_mw")
        lines.append(f"{label} & {item.get('economic_score_pct', 0):.2f}\\% & "
                     f"{('--' if env is None else f'{env:.2f}\\%')} & "
                     f"{('--' if power is None else f'{power:.2f}')} \\\\\\n")
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}"]
    (OUT / "canonical_sensitivity.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    city = d["city_comparison"]["cities"]
    cl = ["\\begin{table}[htbp]", "\\centering",
          "\\caption{Common-model fleet comparison. Vancouver receives full timetable validation; Chicago and London are fleet-level cases.}",
          "\\begin{tabularx}{\\linewidth}{@{}Xrrr@{}}", "\\toprule",
          "Indicator & Vancouver & Chicago & London\\\\", "\\midrule"]
    specs = [("Fleet slot inventory", "fleet_slots", "d"),
             ("Existing electric", "existing_electric", "d"),
             ("Conventional remaining", "conventional_slots", "d"),
             ("Annual service km (million)", "annual_service_km", ".6f"),
             ("Peak annual deliveries", "peak_or_required_annual_delivery", "d"),
             ("Life-cycle environmental score (%)", "lifecycle_environmental_score_pct", ".2f")]
    for title, key, fmt in specs:
        vals = []
        for row in city:
            val = row.get(key)
            if val is None:
                vals.append("--")
            elif key == "annual_service_km":
                vals.append(f"{val/1e6:.2f}")
            elif fmt == ".2f":
                vals.append(f"{val:.2f}")
            else:
                vals.append(f"{int(val):,}")
        cl.append(f"{title} & " + " & ".join(vals) + "\\\\")
    cl += ["\\bottomrule", "\\end{tabularx}", "\\end{table}"]
    (OUT / "three_city_comparison.tex").write_text("\n".join(cl) + "\n", encoding="utf-8")

    points = [x for x in d["transition"].get("weighted_points", [])
              if x.get("full_life_plan_t") is not None and x.get("plan_pv_cad") is not None]
    if points:
        fig, ax = plt.subplots(figsize=(6.6, 3.8))
        ax.scatter([x["plan_pv_cad"] / 1e9 for x in points],
                   [x["full_life_plan_t"] / 1e3 for x in points], s=35)
        ax.set_xlabel("Ten-year gross PV (2023 CAD billion)")
        ax.set_ylabel("Full-life annual emissions (thousand t CO$_2$e/year)")
        ax.set_title("Purchase timing: cost and full-life emissions")
        ax.grid(alpha=.25)
        fig.tight_layout()
        fig.savefig(OUT / "cost_lifecycle_tradeoff.png", dpi=180)
        plt.close(fig)

    print(json.dumps({"macros": len(flat), "sensitivity_rows": len(sens_rows),
                      "fleet_with_spares": d["schedule"]["fleet_with_spares"],
                      "full_life_environment": life["environmental_score_pct"]}, indent=2))


if __name__ == "__main__":
    main()
